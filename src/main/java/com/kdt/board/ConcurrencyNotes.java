package com.kdt.board;

/*
 * =========================================================
 * [ConcurrencyNotes] 동시성 이슈 — 학습용 주석 정리
 * =========================================================
 * ※ 실행 코드 없음. Bean 아님. 개념 노트용 클래스.
 *
 * -------------------------------------------------
 * 1. 동시성 이슈란?
 * -------------------------------------------------
 *   여러 스레드가 같은 데이터를 동시에 건드릴 때,
 *   실행 순서에 따라 결과가 달라지거나 데이터가 깨지는 문제.
 *
 *   "동시성 이슈"가 어렵게 느껴지는 건 "여러 스레드" 때문.
 *   그런데 Spring 웹 서버는 태생이 멀티 스레드다.
 *   요청 100명이 들어오면 톰캣이 스레드 100개(또는 풀 크기만큼)를
 *   만들어 동시에 서비스 코드를 실행한다.
 *   → 동시성 이슈는 특별한 기능이 아니라,
 *     웹 서버를 만드는 순간 자동으로 생기는 위험이다.
 *
 * -------------------------------------------------
 * 2. 편의점 콜라 비유 (race condition)
 * -------------------------------------------------
 *   콜라가 1개 남음. 직원 A·B가 동시에 팔려고 함.
 *
 *   [직원 A] 장부 확인 → 1개 남음
 *   [직원 B] 장부 확인 → 1개 남음   (A가 아직 안 씀)
 *   [직원 A] 1 - 1 = 0 → 장부에 0 씀
 *   [직원 B] 1 - 1 = 0 → 장부에 0 씀
 *
 *   결과: 콜라는 1개인데 손님 2명이 받음.
 *         재고 0, 판매 기록 2건.
 *
 *   핵심: "확인하고 → 계산하고 → 쓰는" 사이에
 *         다른 사람이 끼어들 수 있다.
 *   → 이 끼어듦 = race condition (경쟁 상태)
 *
 * -------------------------------------------------
 * 3. count++ 도 원자적이지 않다
 * -------------------------------------------------
 *   count++ 한 줄이지만 실제로는 3단계:
 *     ① READ  — count 값을 읽는다
 *     ② ADD   — 1을 더한다
 *     ③ WRITE — 결과를 다시 쓴다
 *
 *   스레드 A: READ(0)
 *   스레드 B: READ(0)          ← A가 아직 WRITE 전
 *   스레드 A: ADD → WRITE(1)
 *   스레드 B: ADD → WRITE(1)   ← 덮어씀!
 *
 *   1000번씩 2개 스레드여도 결과가 2000이 아니라
 *   1500, 1800 등으로 나올 수 있음. (콜라 재고와 동일 구조)
 *
 * -------------------------------------------------
 * 4. Spring 재고 차감도 같은 구조
 * -------------------------------------------------
 *   decrease() 안에서:
 *     ① findById → 재고 확인
 *     ② setStock(stock - qty) → 계산
 *     ③ save → 쓰기
 *
 *   1개 남았는데 요청 10건이 동시에 오면
 *   → 10건 모두 ①에서 "재고 있음" → 10건 모두 차감 → 재고 -9
 *   → 초과 판매
 *
 * -------------------------------------------------
 * 5. 깨지는 이유 3가지 (Java 메모리 모델 JMM)
 * -------------------------------------------------
 *   (1) 원자성 없음
 *       "확인 → 계산 → 쓰기"가 한 덩어리로 실행되지 않음
 *       중간에 다른 스레드가 끼어들 수 있음
 *       (count++, 재고 차감)
 *
 *   (2) 가시성 없음
 *       한 스레드가 쓴 값을 다른 스레드가 못 볼 수 있음
 *       (CPU 캐시에만 갱신하고 메인 메모리에 안 쓸 수 있음)
 *       volatile 없는 boolean running → 무한 루프 가능
 *
 *   (3) 재정렬
 *       컴파일러/CPU가 성능을 위해 명령어 순서를 바꿀 수 있음
 *       싱글 스레드에선 문제 없지만,
 *       멀티 스레드에서는 "A가 먼저" 보장이 깨질 수 있음
 *
 *   → synchronized / volatile 이 위 3가지를 보장하는 도구
 *
 * -------------------------------------------------
 * 6. 코드 레벨 해결 (단일 JVM / 단일 서버)
 * -------------------------------------------------
 *   [synchronized]
 *     - 메서드 전체가 "한 스레드만 들어올 수 있는 방"
 *     - 원자성 보장
 *     - 단점: 직렬화로 성능 저하
 *     - 여러 서버에서는 효과 없음 (서버마다 각자 열쇠)
 *
 *   [AtomicInteger]
 *     - "지금 0이면 1로. 아니면 다시 시도" 를 CPU 명령 한 번으로
 *     - synchronized 보다 빠르고 단순 카운터에 최적
 *     - 한계: 변수 1개만. "확인 후 차감" 여러 단계에는 부적합
 *
 *   [volatile]
 *     - 항상 메인 메모리에서 읽고 씀 → 다른 스레드가 즉시 볼 수 있음
 *     - 원자성은 보장 안 함! volatile int + count++ 는 여전히 깨짐
 *     - 플래그 변수에만 사용
 *
 *   [공유하지 않기]
 *     - 불변 객체(record 등): 한 번 만들면 못 바꿈 → 공유해도 안전
 *     - ThreadLocal: 스레드마다 자기 공간
 *       ※ 스레드 풀 재사용 시 반드시 remove() (누수 방지)
 *     - SimpleDateFormat 은 공유하면 깨짐
 *       → DateTimeFormatter(불변) 권장
 *
 *   [동시성 컬렉션]
 *     - ConcurrentHashMap  (HashMap 대신)
 *     - CopyOnWriteArrayList (읽기 많고 쓰기 적을 때)
 *     - HashMap 동시 put → 깨지거나 무한 루프 가능(구버전 유명 버그)
 *     - Collections.synchronizedMap 보다 ConcurrentHashMap 이 우수
 *
 *   ★ 서버 2대 이상이면 코드 레벨 해결책은 전부 무력화
 *     → 부트캠프에서도 DB 레벨이 가장 중요
 *
 * -------------------------------------------------
 * 7. DB 레벨 해결 (다중 서버에서도 유효)
 * -------------------------------------------------
 *   [비관적 락] @Lock(PESSIMISTIC_WRITE) → SELECT … FOR UPDATE
 *     - 조회 시점에 행 락 → 다른 트랜잭션은 대기
 *     - 재고/포인트처럼 충돌이 잦은 곳에 적합
 *     - 단점: 대기·데드락 위험 → 트랜잭션을 짧게
 *
 *   [낙관적 락] @Version
 *     - UPDATE 시 WHERE id=? AND version=? 로 검사
 *     - 충돌 시 OptimisticLockingFailureException → 재시도
 *     - 충돌이 드문 곳(게시글·회원정보)에 적합
 *     - 재고처럼 충돌 잦으면 재시도 폭발로 오히려 느림
 *
 *   [원자적 UPDATE] ★ 재고 차감 실무 1순위
 *     UPDATE … SET stock = stock - :qty
 *     WHERE id = :id AND stock >= :qty
 *     - "확인 + 차감"을 SQL 한 문장으로 → DB가 원자 처리
 *     - 락 대기 없이 빠르고 초과 판매 원천 차단
 *     - 한계: 여러 테이블 연쇄면 SQL로 어렵 → 그때 비관적 락
 *
 * -------------------------------------------------
 * 8. Redis 분산 락 (다중 서버 + 복잡한 로직)
 * -------------------------------------------------
 *   - 여러 서버가 공유하는 락 (SETNX: 먼저 잡으면 다른 서버 못 잡음)
 *   - AOP 순서: 락 Aspect 는 트랜잭션 바깥
 *     → 커밋 후 락이 풀려야 함
 *   - 단점: Redis 장애 시 영향, TTL 설계 필요
 *   - 부트캠프에선 과할 수 있으나 MSA/다중 서버 어필용
 *
 * -------------------------------------------------
 * 9. 선택 가이드
 * -------------------------------------------------
 *   ① 서버 1대 + 충돌 거의 없음
 *      → AtomicInteger, ConcurrentHashMap 등 코드 레벨
 *
 *   ② 재고/포인트/쿠폰처럼 "차감"이 있음 (1대든 N대든)
 *      → 원자적 UPDATE 먼저
 *      → 로직 복잡하면 비관적 락
 *
 *   ③ 충돌 드물고 재시도로 해결 가능
 *      → 낙관적 락 (@Version)
 *
 *   ④ 서버 여러 대 + DB로 표현 어려운 복잡 로직
 *      → Redis 분산 락
 *
 * -------------------------------------------------
 * 10. 흔한 착각
 * -------------------------------------------------
 *   ① "@Transactional 붙이면 동시성 해결"
 *      → 아님. All or Nothing(원자성·커밋/롤백)만 보장
 *        두 트랜잭션이 동시에 같은 재고를 읽는 건 그대로 발생
 *
 *   ② "synchronized 붙이면 끝"
 *      → 서버 2대면 무효
 *        + 트랜잭션 커밋 전에 락이 풀리는 AOP 순서 문제도 가능
 *
 *   ③ "volatile 붙이면 count++ 도 안전"
 *      → 아님. 가시성만 보장. 원자성 없음
 *
 *   ④ "테스트에서 안 터졌으니 괜찮다"
 *      → 동시성 버그는 재현이 안 되는 게 특징
 *        ExecutorService + CountDownLatch 로
 *        스레드 N개를 동시에 던지는 테스트 필수
 *
 * -------------------------------------------------
 * 11. 동시성 테스트 뼈대 (개념)
 * -------------------------------------------------
 *   threadCount = 100
 *   ExecutorService + CountDownLatch(100)
 *   각 스레드: stockService.decrease(1L, 1)
 *   latch.await() 후
 *   assert stock == 0   // -99 가 아니어야 함
 *
 * -------------------------------------------------
 * 12. 한 줄 요약
 * -------------------------------------------------
 *   1) 동시성 = "확인→계산→쓰기" 사이 끼어듦. 웹은 태생이 멀티스레드.
 *   2) 코드 레벨은 단일 서버만. 다중 서버는 DB / Redis.
 *   3) 차감은 원자적 UPDATE 먼저 + 동시성 테스트 필수.
 */
